[CmdletBinding()]
param(
  [string]$ProjectUrl,
  [string]$PublishableKey,
  [string]$AppOrigin
)
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$ConfigPath = Join-Path $Root "config.js"
$SqlPath = Join-Path $Root "KINGDOM_TREASURE_FIRST_INSTALL.sql"

Write-Host "`nKINGDOM TREASURE - SUPABASE CONFIGURATION" -ForegroundColor Cyan
Write-Host "Use the Supabase Project URL and publishable/anon key only."
Write-Host "NEVER paste a service_role or secret key into this script or config.js.`n" -ForegroundColor Yellow

if (-not $ProjectUrl) { $ProjectUrl = Read-Host "Supabase Project URL (https://xxxx.supabase.co)" }
if (-not $PublishableKey) { $PublishableKey = Read-Host "Supabase publishable/anon public key" }
if (-not $AppOrigin) { $AppOrigin = Read-Host "Application URL (e.g. https://username.github.io/repository/)" }

if ($ProjectUrl -notmatch '^https://[a-zA-Z0-9-]+\.supabase\.co/?$') {
  throw "Project URL format is invalid. Expected https://PROJECT-REF.supabase.co"
}
if ($PublishableKey.Length -lt 20 -or $PublishableKey -match 'service_role|secret') {
  throw "The supplied key does not look like a public anon/publishable key. Do not use service_role."
}
if ($AppOrigin -notmatch '^https?://') { throw "App origin must be an absolute http(s) URL." }

$ProjectUrl = $ProjectUrl.TrimEnd('/')
$Config = @"
// Generated by Configure-Supabase.ps1
// This file is browser-visible. Only the public anon/publishable key belongs here.
window.KT_CONFIG = {
  url: "$ProjectUrl",
  anonKey: "$PublishableKey"
};
"@
Set-Content -Path $ConfigPath -Value $Config -Encoding UTF8

Write-Host "`nconfig.js has been configured." -ForegroundColor Green
Write-Host "First-install SQL: $SqlPath"
Write-Host "`nNEXT STEPS:"
Write-Host "1. Open Supabase Dashboard > SQL Editor > New query."
Write-Host "2. Open KINGDOM_TREASURE_FIRST_INSTALL.sql, copy all, paste and Run."
Write-Host "3. In Authentication > URL Configuration, set Site URL to:"
Write-Host "   $AppOrigin"
Write-Host "4. Add this URL and http://localhost:8000 to Redirect URLs."
Write-Host "5. Enable email confirmations and configure SMTP before production."
Write-Host "`nThis script does NOT deploy SQL or create a Supabase project; those require your authenticated Supabase account."
